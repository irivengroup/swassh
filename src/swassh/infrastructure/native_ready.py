"""Private, literal OpenSSH LocalCommand acknowledgement for Windows scopes.

Windows OpenSSH opens -E logs without FILE_SHARE_READ. A callback generated by
this adapter records authentication/forward setup without reading that live
file or mixing client diagnostics into either remote byte stream. No endpoint,
user command or OpenSSH percent token enters the local shell command.
"""
from __future__ import annotations

import base64
import binascii
import json
import os
from pathlib import Path
import secrets
import stat
import subprocess
import sys

from .filesystem import AtomicOutput, PinnedDirectory


class NativeReady:
    """One random acknowledgement in an already private scope directory."""
    def __init__(self, root):
        self.path = Path(root).absolute() / 'authenticated'
        self.token = secrets.token_hex(32)

    def command(self):
        """Return only a trusted interpreter, fixed module and bounded envelope."""
        if any(character in sys.executable for character in '%!&|<>^\r\n\0"'):
            raise ValueError('native readiness requires a literal Windows interpreter path')
        raw = json.dumps([str(self.path), self.token], ensure_ascii=True).encode('ascii')
        if len(raw) > 2048:
            raise ValueError('native readiness request exceeds its budget')
        return subprocess.list2cmdline([sys.executable, '-m', __name__,
            base64.urlsafe_b64encode(raw).decode('ascii')])

    def observed(self):
        """Refuse malformed or oversized acknowledgements; absence is not ready."""
        try:
            with PinnedDirectory(self.path.parent, private=True) as directory:
                fd = directory.open(self.path.name, os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0) | getattr(os, 'O_NONBLOCK', 0))
                with os.fdopen(fd, 'rb') as stream:
                    info = os.fstat(stream.fileno())
                    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                        raise ValueError('native readiness must be a regular file without hard links')
                    data = stream.read(65)
        except FileNotFoundError:
            return False
        if data != self.token.encode('ascii'):
            raise ValueError('native readiness acknowledgement mismatch')
        return True

    @staticmethod
    def record(envelope):
        """Validate a local callback request and atomically write its exact token."""
        try:
            if not isinstance(envelope, str) or len(envelope) > 4096:
                raise ValueError('oversized request')
            raw = base64.b64decode(envelope, altchars=b'-_', validate=True)
            if len(raw) > 2048:
                raise ValueError('oversized decoded request')
            value = json.loads(raw.decode('ascii'))
            if (not isinstance(value, list) or len(value) != 2
                    or not all(isinstance(item, str) for item in value)):
                raise ValueError('invalid fields')
            path, token = value
            if (Path(path).name != 'authenticated' or not Path(path).is_absolute()
                    or len(token) != 64 or any(char not in '0123456789abcdef' for char in token)):
                raise ValueError('invalid acknowledgement')
        except (ValueError, UnicodeError, binascii.Error, RecursionError):
            raise ValueError('invalid native readiness request') from None
        with PinnedDirectory(Path(path).parent, private=True):
            with AtomicOutput(path) as stream:
                stream.write(token)


def main(arguments=None):
    """Fixed internal callback; never executes the decoded request as code."""
    arguments = sys.argv[1:] if arguments is None else arguments
    if len(arguments) != 1:
        raise ValueError('native readiness requires exactly one request')
    NativeReady.record(arguments[0])


if __name__ == '__main__':
    main()
