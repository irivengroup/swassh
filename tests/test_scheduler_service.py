"""Concrete OS service files, safe escaping and exclusive file creation."""
import contextlib
import io
import plistlib
import runpy
import tempfile
import unittest
import xml.etree.ElementTree as ET
from pathlib import Path

MODULE = runpy.run_path(str(Path(__file__).resolve().parents[1] / 'scripts/scheduler_service.py'))


class ServiceTests(unittest.TestCase):
    def test_systemd_escaping_and_process_group_cleanup(self):
        name, data = MODULE['generate']('systemd', '/opt/venv/bin/python', '/tmp/a $b%"quoted')
        text = data.decode()
        self.assertEqual(name, 'swassh-scheduler.service')
        self.assertIn('KillMode=control-group', text)
        self.assertIn('$$b%%\\"quoted', text)
        self.assertIn('UMask=0077', text)
        self.assertNotIn('PrivateTmp', text)

    def test_launchd_and_windows_native_argument_arrays(self):
        name, data = MODULE['generate']('launchd', '/opt/venv/bin/python', '/tmp/state with spaces')
        value = plistlib.loads(data)
        self.assertEqual(value['ProgramArguments'][-1], str(Path('/tmp/state with spaces').absolute()))
        self.assertTrue(value['KeepAlive'])
        name, data = MODULE['generate']('windows', '/opt/python', '/tmp/state with spaces', 'DOMAIN\\user')
        task = ET.fromstring(data)
        ns = {'t': 'http://schemas.microsoft.com/windows/2004/02/mit/task'}
        self.assertEqual(task.find('t:Principals/t:Principal/t:UserId', ns).text, 'DOMAIN\\user')
        self.assertEqual(task.find('t:Settings/t:ExecutionTimeLimit', ns).text, 'PT0S')
        self.assertIn(MODULE['windows_arguments']([str(Path('/tmp/state with spaces').absolute())]), task.find('t:Actions/t:Exec/t:Arguments', ns).text)
        MODULE['generate']('windows', '/opt/python', '/tmp/state')
        self.assertEqual(MODULE['windows_arguments'](['a"b', 'ends\\']), '"a\\"b" "ends\\\\"')
        with self.assertRaises(ValueError):
            MODULE['generate']('invalid', '/opt/python', '/tmp/state')
        with self.assertRaises(ValueError):
            MODULE['absolute']('/tmp/state\n')

    def test_generator_creates_full_service_and_refuses_overwrite(self):
        with tempfile.TemporaryDirectory() as directory:
            args = ['--platform', 'systemd', '--state-dir', str(Path(directory) / 'state'),
                    '--output-dir', directory]
            with contextlib.redirect_stdout(io.StringIO()):
                MODULE['main'](args)
            self.assertTrue((Path(directory) / 'swassh-scheduler.service').read_text())
            with self.assertRaises(FileExistsError):
                MODULE['main'](args)


    def test_unicode_definitions_and_output_paths_survive_legacy_streams(self):
        """Generated bytes stay Unicode; only unrepresentable display characters escape."""
        for encoding in ('ascii', 'cp1252', 'utf-8'):
            for platform in ('systemd', 'launchd', 'windows', 'smf', 'src'):
                with self.subTest(encoding=encoding, platform=platform), tempfile.TemporaryDirectory() as directory:
                    output = Path(directory)/'service-漢字-été'
                    state = Path(directory)/'etat-漢字-été'
                    buffer = io.BytesIO()
                    stream = io.TextIOWrapper(buffer, encoding=encoding, errors='strict')
                    args = ['--platform', platform, '--state-dir', str(state),
                            '--output-dir', str(output), '--user', 'synthetic-user']
                    try:
                        with contextlib.redirect_stdout(stream):
                            MODULE['main'](args)
                        stream.flush()
                        files = sorted(output.iterdir())
                        self.assertEqual(len(files), 2 if platform == 'smf' else 1)
                        expected = [str(path.absolute()) for path in files]
                        displayed = buffer.getvalue().decode(encoding).splitlines()
                        self.assertEqual(sorted(displayed), sorted(value.encode(encoding, errors='backslashreplace').decode(encoding) for value in expected))
                        self.assertTrue(all(path.read_bytes() for path in files))
                        definitions = [path for path in files if path.suffix != '.sh']
                        for path in definitions:
                            if path.suffix == '.xml':
                                ET.fromstring(path.read_bytes())
                            elif path.suffix == '.plist':
                                plistlib.loads(path.read_bytes())
                        self.assertTrue(any('漢字-été'.encode('utf-8') in path.read_bytes() for path in files))
                        if encoding == 'utf-8':
                            self.assertTrue(all('漢字' in value for value in displayed))
                    finally:
                        stream.close()

    def test_real_output_errors_still_fail_after_exclusive_generation(self):
        """Encoding compatibility must not hide genuine I/O failure or permit overwrite."""
        class BrokenOutput:
            encoding = 'utf-8'
            def write(self, text):
                raise OSError('synthetic output failure')
            def flush(self):
                return None
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)/'service-漢字'
            args = ['--platform', 'windows', '--state-dir', str(Path(directory)/'state'),
                    '--output-dir', str(output), '--user', 'synthetic-user']
            with contextlib.redirect_stdout(BrokenOutput()), self.assertRaisesRegex(OSError, 'synthetic output failure'):
                MODULE['main'](args)
            path = output/'swassh-scheduler.xml'
            original = path.read_bytes()
            ET.fromstring(original)
            with contextlib.redirect_stdout(io.StringIO()), self.assertRaises(FileExistsError):
                MODULE['main'](args)
            self.assertEqual(path.read_bytes(), original)
